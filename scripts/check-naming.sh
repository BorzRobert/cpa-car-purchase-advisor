#!/bin/sh
# Single source of truth for the branch and commit naming rules, shared by the local git hooks and the CI job
# (.github/workflows/naming.yml), so the rule cannot drift between them.
#
# Usage:
#   sh scripts/check-naming.sh branch <name>     branch must be CPA-<issue number>-<kebab-message> (main is exempt)
#   sh scripts/check-naming.sh message <subject> subject must be CPA-<issue number> <message> (Merge/Revert exempt)
#   sh scripts/check-naming.sh id <name-or-subject>  prints the issue number, or nothing if there is none

set -eu

BRANCH_RE='^CPA-[0-9]+-[a-z0-9]+(-[a-z0-9]+)*$'
MESSAGE_RE='^CPA-[0-9]+ [^[:space:]].*$'

mode="${1-}"
value="${2-}"

case "$mode" in
  branch)
    [ "$value" = "main" ] && exit 0
    if ! printf '%s' "$value" | grep -Eq "$BRANCH_RE"; then
      echo "Invalid branch name: '$value'" >&2
      echo "Required format: CPA-<issue number>-<kebab-message>, e.g. CPA-42-add-google-login" >&2
      exit 1
    fi
    ;;
  message)
    # Messages generated by git for merges and reverts cannot be rewritten by us.
    case "$value" in
      Merge\ * | Revert\ *) exit 0 ;;
    esac
    if ! printf '%s' "$value" | grep -Eq "$MESSAGE_RE"; then
      echo "Invalid commit message / PR title: '$value'" >&2
      echo "Required format: CPA-<issue number> <message>, e.g. CPA-42 Add Google login" >&2
      exit 1
    fi
    ;;
  id)
    printf '%s\n' "$value" | sed -nE 's/^CPA-([0-9]+)([- ].*)?$/\1/p'
    ;;
  *)
    echo "usage: $0 branch|message|id <value>" >&2
    exit 2
    ;;
esac
